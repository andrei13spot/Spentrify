import { Ionicons } from "@expo/vector-icons";
import * as FileSystem from "expo-file-system/legacy";
import * as Sharing from "expo-sharing";
import React, { useState } from "react";
import {
  ActivityIndicator,
  Alert,
  Modal,
  Pressable,
  ScrollView,
  StyleSheet,
  Text,
  View,
} from "react-native";

/* ================= TYPES ================= */

export type ReportData = {
  title: string;
  budgetName: string;
  budget: number;
  spent: number;
  remaining: number;
  percentageUsed: number;
  createdAt: string;
  description?: string;
};

type ReportPreviewModalProps = {
  visible: boolean;
  reportData: ReportData | null;
  onClose: () => void;
};

/* ================= COMPONENT ================= */

export default function ReportPreviewModal({
  visible,
  reportData,
  onClose,
}: ReportPreviewModalProps) {
  const [downloading, setDownloading] = useState(false);
  const [sharing, setSharing] = useState(false);

  if (!reportData) return null;

  /* ================= GENERATE REPORT CONTENT ================= */

  const generateReportContent = (): string => {
    const date = new Date(reportData.createdAt).toLocaleDateString("en-US", {
      year: "numeric",
      month: "long",
      day: "numeric",
    });

    return `
═══════════════════════════════════════════════════════
              SPENTRIFY FINANCIAL REPORT
═══════════════════════════════════════════════════════

Report Title: ${reportData.title}
Generated: ${new Date().toLocaleDateString("en-US", {
      year: "numeric",
      month: "long",
      day: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    })}

───────────────────────────────────────────────────────
                    BUDGET SUMMARY
───────────────────────────────────────────────────────

Budget Name: ${reportData.budgetName}
Created: ${date}

Budget Amount:     ₱${reportData.budget.toLocaleString()}
Amount Spent:      ₱${reportData.spent.toLocaleString()}
Remaining:         ₱${reportData.remaining.toLocaleString()}
Usage Percentage:  ${reportData.percentageUsed.toFixed(1)}%

───────────────────────────────────────────────────────
                    INSIGHTS
───────────────────────────────────────────────────────

${reportData.description || "No additional insights available."}

───────────────────────────────────────────────────────

This report was generated by Spentrify.
For questions or support, please contact your administrator.

═══════════════════════════════════════════════════════
`.trim();
  };

  /* ================= DOWNLOAD REPORT ================= */

  const handleDownload = async () => {
    if (!reportData) return;

    try {
      setDownloading(true);

      const content = generateReportContent();
      const fileName = `Spentrify_Report_${reportData.budgetName.replace(
        /\s+/g,
        "_"
      )}_${Date.now()}.txt`;
      // @ts-ignore - documentDirectory exists at runtime
      const documentDir = FileSystem.documentDirectory || '';
      const fileUri = documentDir + fileName;

      // Write file to device storage
      await FileSystem.writeAsStringAsync(fileUri, content);

      Alert.alert(
        "Download Complete",
        `Report saved as ${fileName}`,
        [{ text: "OK" }]
      );
    } catch (error) {
      console.error("Error downloading report:", error);
      Alert.alert(
        "Download Failed",
        "Unable to download the report. Please try again.",
        [{ text: "OK" }]
      );
    } finally {
      setDownloading(false);
    }
  };

  /* ================= SHARE REPORT ================= */

  const handleShare = async () => {
    if (!reportData) return;

    try {
      setSharing(true);

      const content = generateReportContent();
      const fileName = `Spentrify_Report_${reportData.budgetName.replace(
        /\s+/g,
        "_"
      )}_${Date.now()}.txt`;
      // @ts-ignore - documentDirectory exists at runtime
      const documentDir = FileSystem.documentDirectory || '';
      const fileUri = documentDir + fileName;

      // Write file to device storage
      await FileSystem.writeAsStringAsync(fileUri, content);

      // Check if sharing is available
      const isAvailable = await Sharing.isAvailableAsync();
      if (!isAvailable) {
        Alert.alert(
          "Sharing Not Available",
          "Sharing is not available on this device.",
          [{ text: "OK" }]
        );
        return;
      }

      // Share the file
      await Sharing.shareAsync(fileUri, {
        mimeType: "text/plain",
        dialogTitle: "Share Financial Report",
      });
    } catch (error) {
      console.error("Error sharing report:", error);
      Alert.alert(
        "Share Failed",
        "Unable to share the report. Please try again.",
        [{ text: "OK" }]
      );
    } finally {
      setSharing(false);
    }
  };

  /* ================= RENDER ================= */

  return (
    <Modal
      visible={visible}
      transparent
      animationType="slide"
      onRequestClose={onClose}
    >
      <View style={styles.overlay}>
        <View style={styles.modalContainer}>
          {/* HEADER */}
          <View style={styles.header}>
            <Text style={styles.headerTitle}>Report Preview</Text>
            <Pressable onPress={onClose} hitSlop={10}>
              <Ionicons name="close" size={24} color="#111827" />
            </Pressable>
          </View>

          {/* PREVIEW CONTENT */}
          <ScrollView
            style={styles.previewContainer}
            contentContainerStyle={styles.previewContent}
            showsVerticalScrollIndicator={true}
          >
            <View style={styles.reportContent}>
              <Text style={styles.reportTitle}>{reportData.title}</Text>
              <Text style={styles.reportMeta}>
                Generated: {new Date().toLocaleDateString()}
              </Text>

              <View style={styles.section}>
                <Text style={styles.sectionTitle}>Budget Summary</Text>
                <View style={styles.summaryRow}>
                  <Text style={styles.summaryLabel}>Budget Name:</Text>
                  <Text style={styles.summaryValue}>{reportData.budgetName}</Text>
                </View>
                <View style={styles.summaryRow}>
                  <Text style={styles.summaryLabel}>Budget Amount:</Text>
                  <Text style={styles.summaryValue}>
                    ₱{reportData.budget.toLocaleString()}
                  </Text>
                </View>
                <View style={styles.summaryRow}>
                  <Text style={styles.summaryLabel}>Amount Spent:</Text>
                  <Text style={styles.summaryValue}>
                    ₱{reportData.spent.toLocaleString()}
                  </Text>
                </View>
                <View style={styles.summaryRow}>
                  <Text style={styles.summaryLabel}>Remaining:</Text>
                  <Text style={styles.summaryValue}>
                    ₱{reportData.remaining.toLocaleString()}
                  </Text>
                </View>
                <View style={styles.summaryRow}>
                  <Text style={styles.summaryLabel}>Usage:</Text>
                  <Text style={styles.summaryValue}>
                    {reportData.percentageUsed.toFixed(1)}%
                  </Text>
                </View>
              </View>

              {reportData.description && (
                <View style={styles.section}>
                  <Text style={styles.sectionTitle}>Insights</Text>
                  <Text style={styles.descriptionText}>
                    {reportData.description}
                  </Text>
                </View>
              )}

              <View style={styles.footer}>
                <Text style={styles.footerText}>
                  Generated by Spentrify
                </Text>
              </View>
            </View>
          </ScrollView>

          {/* ACTION BUTTONS */}
          <View style={styles.actions}>
            <Pressable
              style={[styles.actionButton, styles.downloadButton]}
              onPress={handleDownload}
              disabled={downloading || sharing}
            >
              {downloading ? (
                <ActivityIndicator color="#FFFFFF" size="small" />
              ) : (
                <>
                  <Ionicons name="download-outline" size={20} color="#FFFFFF" />
                  <Text style={styles.actionButtonText}>Download</Text>
                </>
              )}
            </Pressable>

            <Pressable
              style={[styles.actionButton, styles.shareButton]}
              onPress={handleShare}
              disabled={downloading || sharing}
            >
              {sharing ? (
                <ActivityIndicator color="#FFFFFF" size="small" />
              ) : (
                <>
                  <Ionicons name="share-outline" size={20} color="#FFFFFF" />
                  <Text style={styles.actionButtonText}>Share</Text>
                </>
              )}
            </Pressable>
          </View>
        </View>
      </View>
    </Modal>
  );
}

